// Keep the VM image contract portable in both CommonJS and ESM packages.
const archiver = require("archiver");
const { readFileSync, readdirSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

async function main() {
  const root = join(__dirname, "..");
  const directory = join(root, "lib/resources/abstraction/vm-assets");
  const archive = archiver("tar", { gzip: true });
  const chunks = [];
  const complete = new Promise((resolve, reject) => {
    archive.on("data", (chunk) => chunks.push(chunk));
    archive.on("error", reject);
    archive.on("end", () => resolve(Buffer.concat(chunks)));
  });
  for (const name of readdirSync(directory).sort()) {
    archive.append(readFileSync(join(directory, name)), {
      name,
      date: new Date(0),
      mode: /\.(service|html|desktop|svg)$/.test(name) ? 0o644 : 0o755,
    });
  }
  await archive.finalize();
  const payload = (await complete).toString("base64");
  writeFileSync(
    join(root, "lib/resources/abstraction/vm-image-assets.ts"),
    `// Generated by scripts/generate-vm-assets.cjs from the Python-compatible VM assets.\nexport const VM_IMAGE_ASSETS = ${JSON.stringify(payload)};\n`,
  );
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
